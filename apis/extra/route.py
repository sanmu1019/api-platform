@router.get("/number/upper", name="number_to_upper")
def number_to_upper(number: str = Query(..., description="数字，如 1234.56")):
    """人民币金额小写转大写。"""
    try:
        n = float(number)
    except ValueError:
        return {"code": 400, "msg": "无效数字", "data": None}

    digits = "零壹贰叁肆伍陆柒捌玖"
    units = ["", "拾", "佰", "仟"]
    big_units = ["", "万", "亿", "兆"]

    def int_to_cn(num: int) -> str:
        if num == 0:
            return "零"
        result = ""
        group_idx = 0
        while num > 0:
            group = num % 10000
            if group != 0:
                g = ""
                zero_flag = False
                for i in range(4):
                    d = group % 10
                    if d == 0:
                        zero_flag = True
                    else:
                        if zero_flag:
                            g = "零" + g
                            zero_flag = False
                        g = digits[d] + units[i] + g
                    group //= 10
                result = g + big_units[group_idx] + result
            group_idx += 1
            num //= 10000
        return result

    int_part = int(n)
    dec_part = round((n - int_part) * 100)
    jiao = dec_part // 10
    fen = dec_part % 10

    result = int_to_cn(int_part) + "元"
    if jiao == 0 and fen == 0:
        result += "整"
    else:
        if jiao > 0:
            result += digits[jiao] + "角"
        if fen > 0:
            result += digits[fen] + "分"

    return {"code": 200, "msg": "success", "data": {"number": number, "upper": result}}


