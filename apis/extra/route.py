@router.get("/ping", name="ping_check")
def ping_check(host: str = Query(..., description="域名或IP，如 baidu.com")):
    """检测主机是否可达（TCP 80/443）。"""
    host = host.strip().replace("https://", "").replace("http://", "").split("/")[0]
    results = []
    for port in (80, 443):
        try:
            sock = socket.create_connection((host, port), timeout=3)
            sock.close()
            results.append({"port": port, "reachable": True})
        except Exception:
            results.append({"port": port, "reachable": False})
    reachable = any(r["reachable"] for r in results)
    return {
        "code": 200,
        "msg": "success",
        "data": {"host": host, "reachable": reachable, "ports": results},
    }


